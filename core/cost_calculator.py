_누진_구간 = [
    (100_000_000,  200_000_000,  0.0009),   # 1억~2억 초과분
    (200_000_000,  500_000_000,  0.0007),   # 2억~5억
    (500_000_000,  1_000_000_000, 0.0005),  # 5억~10억
    (1_000_000_000, 2_000_000_000, 0.0003), # 10억~20억
    (2_000_000_000, float("inf"), 0.00016), # 20억 초과
]


def calc_보수료_이전(목적가액: int) -> dict:
    """소유권이전등기 보수료 (기본보수 + 누진료)"""
    # 기본보수
    기본보수 = _보수_기본표[-1][1]
    for 상한, 보수 in _보수_기본표:
        if 목적가액 <= 상한:
            기본보수 = 보수
            break

    # 누진료
    누진료 = 0
    if 목적가액 > 100_000_000:
        prev = 100_000_000
        for 시작, 끝, 율 in _누진_구간:
            if 목적가액 <= 시작:
                break
            초과분 = min(목적가액, 끝) - max(prev, 시작)
            if 초과분 > 0:
                누진료 += 초과분 * 율
            prev = 끝

    보수료합계 = _round10(기본보수 + 누진료)
    부가세 = _round10(보수료합계 * 0.1)

    return {"보수료": 보수료합계, "부가세_이전": 부가세}


