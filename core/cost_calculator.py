def calc_인지대_이전(취득가액: int) -> int:
    """소유권이전 인지대 — 매수인 단독 부담"""
    for 상한, 금액 in _인지대_이전_구간:
        if 취득가액 < 상한:
            return 금액
    return 350_000


def calc_인지대_설정(채권최고액: int) -> int:
    """근저당설정 인지대"""
    for 상한, 금액 in _인지대_설정_구간:
        if 채권최고액 < 상한:
            return 금액
    return 350_000


